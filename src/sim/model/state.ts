import type { RngStreams } from '../core/rng';
import type { Pace } from '../config';

/**
 * Reference to player-facing text. The simulation never stores sentences, only
 * translation keys + parameters; the UI translates them (src/i18n).
 */
export interface TextRef {
  key: string;
  params?: Record<string, string | number>;
}

/** Visual appearance of an Empirian. Indices refer to catalogs in content/appearance. */
export interface Appearance {
  skin: number;
  hairStyle: number;
  hairColor: number;
  top: number;
  topColor: number;
  pantsColor: number;
  accessory: number; // 0 = none
}

export type Activity =
  | 'idle'
  | 'coding'
  | 'designing'
  | 'testing'
  | 'thinking'
  | 'raising_hand'
  | 'celebrating'
  | 'resting'
  /** Short breaks (AW.B). */
  | 'drinking'
  | 'lounging'
  | 'chatting';

export type SkillId = 'tech' | 'design' | 'creativity' | 'management';

export interface Empirian {
  id: string;
  name: string;
  /** Optional nickname chosen by the player (AW.C). */
  nickname?: string;
  appearance: Appearance;
  /** Current levels (1-10, fractional). Derived from baseSkills + xp (systems/progression.ts). */
  skills: Record<SkillId, number>;
  /** Starting levels (future: founder origins). */
  baseSkills: Record<SkillId, number>;
  /** Experience earned by doing each kind of activity. */
  xp: Record<SkillId, number>;
  /** Experience per game topic (specialization). */
  topicXp: Record<string, number>;
  energy: number; // 0-100
  morale: number; // 0-100
  activity: Activity;
  /** Employees only (GT.1): weekly salary, personality trait and hiring day. The founder has none. */
  salary?: number;
  trait?: TraitId;
  hiredDay?: number;
  /** Short break in progress until this tick (AW.B routines). */
  breakUntil?: number;
  breakKind?: BreakKind;
  /** Day of the last break (at most one per day). */
  lastBreakDay?: number;
  /** Who they're chatting with during a chat break. */
  chatWith?: string;
  /** Assigned role (AW.E.2). Missing or 'auto' = they do what the project needs. */
  role?: Role;
}

export type Role = 'auto' | 'design' | 'code' | 'test';

export type BreakKind = 'drink' | 'rest' | 'chat';

/** Professional relationship between two Empirians (E.3 / D-056). `a` < `b`. */
export interface Relation {
  a: string;
  b: string;
  /** −100 (rivals) … 100 (close friends). Only facts change it. */
  bond: number;
  /** Working days spent together. */
  days: number;
  /** Launches shipped together, and how many were hits. */
  shared: number;
  hits: number;
  /** Day they met. */
  since: number;
  /** Who mentors whom right now, and in what. */
  mentor?: string;
  mentorSkill?: SkillId;
  /** This pair already had its mentoring. */
  mentorDone?: boolean;
}

export type RelationKind = 'friends' | 'good_team' | 'respect' | 'mentor' | 'tension' | 'rivals';

/** Personality traits (GT.1/GT.2). Each one helps in something and costs in something else. */
export type TraitId = 'perfectionist' | 'night_owl' | 'sociable' | 'curious';

/** A job applicant (GT.1). Generated by the seed; becomes an Empirian when hired. */
export interface Candidate {
  id: string;
  name: string;
  appearance: Appearance;
  baseSkills: Record<SkillId, number>;
  trait: TraitId;
  /** Weekly salary asked. */
  salary: number;
  expiresDay: number;
}

/** Studio memories (ML.2): meaningful moments, derived from real facts. */
export type MemoryKind =
  | 'founded' | 'first_release' | 'first_hit' | 'first_flop' | 'hit' | 'record' | 'comeback'
  | 'first_hire' | 'hire' | 'farewell' | 'first_contract' | 'skill_master' | 'money' | 'decision' | 'first_decor' | 'achievement' | 'office_moved' | 'relation';

export interface Memory {
  id: string;
  day: number;
  kind: MemoryKind;
  text: TextRef;
  tone: -1 | 0 | 1;
  empirianIds?: string[];
  projectId?: string;
  /** Dedupe id of the fact: a fact becomes a memory only once. */
  fact: string;
}

export interface Story {
  memories: Memory[];
  /** Achievement id → day it was earned (ML.3). */
  achievements: Record<string, number>;
  /** Ledger entries up to this tick were already scanned for big decisions. */
  scannedTick: number;
  /** Released projects already evaluated as (possibly) memorable. */
  seenReleases: string[];
}

/** In-game tutorial progress (AW.A). Steps complete from real facts; `marks` record UI-only facts. */
export interface Tutorial {
  active: boolean;
  marks: string[];
  /** Counts when the tutorial (re)started: steps compare against them so a restart is meaningful. */
  base: { projects: number; released: number; decisions: number; purchases: number };
  finishedDay?: number;
}

export interface Hiring {
  candidates: Candidate[];
  nextRefreshDay: number;
  hired: number;
  salariesPaid: number;
}

export type ProjectPhase = 'concept' | 'production' | 'polish' | 'released';
export type ProjectSize = 'small' | 'medium';

export interface DecisionOption {
  id: string;
  label: TextRef;
  /** Short, uncertain hints shown to the player (estimates, not exact values). */
  hints: TextRef[];
  disabledReason?: TextRef;
}

export interface PendingDecision {
  id: string;
  kind: 'big_idea' | 'deadline' | 'exhausted' | 'running_late' | 'polish_plan' | 'feature_trouble' | 'prototype_result' | 'streamer_preview' | 'rival_similar' | 'critical_bug' | 'unexpected_idea'
    | 'tech_shortcut' | 'debt_review' | 'scope_idea'
    | 'team_idea' | 'contract_change' | 'game_fair' | 'influential_review' | 'team_debate' | 'training_request';
  speakerId: string;
  text: TextRef;
  options: DecisionOption[];
  createdTick: number;
  /** Data the event needs to resolve (dynamic events, LS.7). */
  context?: Record<string, string | number>;
}

export interface Review {
  outlet: string;
  score: number; // 1-10, one decimal
  quote: TextRef;
}

export interface ProjectResult {
  releasedDay: number;
  price: number;
  reviews: Review[];
  averageScore: number;
  weeklySales: number[]; // units per week so far
  totalUnits: number;
  revenue: number;
  /** Causal ledger ids explaining the score, most relevant first. */
  explanation: string[];
  /** Long-tail sales after the launch weeks (LS.6). */
  tailWeeks?: number;
  tailUnits?: number;
  /** True once sales have dried up. */
  salesEnded?: boolean;
  /** Temporary sales multiplier (patches, scandals). */
  salesBoost?: { factor: number; untilDay: number };
  /** An influential critic already covered it (story event). */
  criticCovered?: boolean;
}

export interface Project {
  id: string;
  name: string;
  topicId: string;
  size: ProjectSize;
  /** 0 = pure design, 1 = pure tech. */
  focus: number;
  pace: Pace;
  phase: ProjectPhase;
  startDay: number;
  /** Day the product was announced to be ready. Can be changed by the player. */
  deadlineDay: number;
  originalDeadlineDay: number;
  budget: number;
  spent: number;
  /** Retail price chosen by the player. */
  price: number;
  requiredPoints: number;
  /** Production work done (design + tech). */
  workDone: { design: number; tech: number };
  /** Extra quality-earning polish work after production. */
  polishDone: number;
  testingDone: number;
  /** Additive modifiers to the quality ceiling, each tied to a ledger entry. */
  ceilingMods: { amount: number; causeId: string }[];
  bugRateMods: { factor: number; causeId: string }[];
  bugs: { hidden: number; known: number; fixed: number };
  hype: number;
  /** Fraction of polish-phase work devoted to testing/fixing (0-1). */
  testFocus: number;
  decisionsTaken: string[];
  /** Chosen features (AW.D.1) and what happened to their hidden risks. */
  features?: string[];
  featureTrouble?: string[];
  featureResolved?: string[];
  featureDropped?: string[];
  featureIgnored?: string[];
  /** Prototype (AW.D.2): planned, finished, and whether it validated the idea. */
  prototype?: boolean;
  prototypeDone?: boolean;
  prototypeValidated?: boolean;
  bigIdeaOffered: boolean;
  /** Contextual moments already offered in this project (systems/moments.ts). */
  momentsOffered?: string[];
  lastMomentDay?: number;
  /** The team is taking days off until this day (no work, extra recovery). */
  restUntilDay?: number;
  /** Dynamic events already seen in this project (LS.7). */
  previewGiven?: string;
  eventsSeen?: number;
  /** Technical debt of this project's code, 0…100 (F3.4), and what caused it. */
  debt?: number;
  debtCauses?: string[];
  /** Story events already raised for this project (each one at most once). */
  storyEvents?: string[];
  rivalAnnounced?: boolean;
  ideaOffered?: boolean;
  bugReported?: boolean;
  /** Set once its routine history has been archived (systems/history.ts). */
  historyCompacted?: boolean;
  result?: ProjectResult;
}

export interface LedgerEntry {
  id: string;
  tick: number;
  day: number;
  kind: string;
  text: TextRef;
  causes: string[];
  /** Sign of the effect on product outcome: +1 good, -1 bad, 0 neutral. */
  tone: -1 | 0 | 1;
  projectId?: string;
}

export type NewsKind =
  | 'trend_rising' | 'trend_peak' | 'trend_over' | 'competitor_release' | 'economy_up' | 'economy_down'
  | 'tool_tech' | 'tool_design' | 'revival';

export interface NewsItem {
  id: string;
  day: number;
  kind: NewsKind;
  /** Parameters for the headline/consequence texts (`news.<kind>.title` / `.body`). */
  params: Record<string, string | number>;
  importance: 'major' | 'minor';
}

export interface Trend {
  id: string;
  topicId: string;
  startDay: number;
  peakDay: number;
  endDay: number;
  /** Extra demand at the peak (0.5 = +50 %). */
  strength: number;
  peakAnnounced: boolean;
  endAnnounced: boolean;
}

/** The world outside the studio (LS.5, Empires Daily). */
export interface World {
  trends: Trend[];
  /** Saturation per topic from competitors' releases (decays weekly). */
  competition: Record<string, number>;
  /** Sales multiplier from the general economy (~0.85–1.15). */
  economy: number;
  /** Temporary speed-up of one kind of work (tech news). */
  toolBoost: { kind: 'tech' | 'design'; factor: number; untilDay: number } | null;
  news: NewsItem[];
  nextTrendDay: number;
  lastReadNewsId: string | null;
  /** Products whose topic is having a revival, until the given day. */
  revivals: Record<string, number>;
}

export interface ContractOffer {
  id: string;
  clientId: string;
  kind: string;
  /** Share of technical work (0..1). */
  focus: number;
  /** Work points to deliver. */
  work: number;
  /** Days allowed from acceptance. */
  days: number;
  payment: number;
  expiresDay: number;
}

export interface ActiveContract extends ContractOffer {
  startDay: number;
  dueDay: number;
  done: number;
  causeId: string;
  /** The client already asked for changes (story event). */
  renegotiated?: boolean;
}

/** External contracts (LS.8). */
export interface Contracts {
  offers: ContractOffer[];
  active: ActiveContract | null;
  nextRefreshDay: number;
  completed: number;
}

export type Rot = 0 | 1 | 2 | 3;

/** A catalog item placed in the office (LS.2). Coordinates are grid cells. */
export interface PlacedItem {
  uid: string;
  defId: string;
  x: number;
  z: number;
  rot: Rot;
  /** Desks hold a computer and a chair (catalog ids). */
  mounts?: { computer?: string; chair?: string };
  /** Desk taken by an employee (GT.1). Unassigned desks: the founder uses the best one. */
  assignedTo?: string;
}

export interface Office {
  w: number;
  d: number;
  items: PlacedItem[];
  /** Wall and floor finishes (AW.C.3). Missing = the original cream walls and oak floor. */
  style?: { wall: string; floor: string };
  /** Office size (AW.E.1). Missing = the starting room. */
  size?: 'room' | 'studio';
}

export interface GameState {
  schemaVersion: number;
  seed: number;
  rng: RngStreams;
  tick: number;
  day: number;
  nextId: number;
  company: {
    name: string;
    money: number;
    reputation: number; // 0-100
    /** Ideas saved for later (ledger ids), used by the next projects. */
    savedIdeas?: string[];
    /** Technical debt left in the studio's code for the next game (F3.4). */
    techDebt?: number;
    /** A solid base built in a past project (ledger id): the next game needs less work. */
    solidBase?: string;
  };
  founderId: string;
  empirians: Empirian[];
  projects: Project[];
  activeProjectId: string | null;
  pendingDecision: PendingDecision | null;
  ledger: LedgerEntry[];
  /** Trend multiplier per topic id (market drift). */
  topicTrends: Record<string, number>;
  /** Set until the founder has been customized. */
  setupComplete: boolean;
  office: Office;
  world: World;
  contracts: Contracts;
  /** Team growth (GT.1). */
  hiring: Hiring;
  /** Memories and achievements (ML.2, ML.3). */
  story: Story;
  /** Professional relationships (E.3). Optional: older saves start with none. */
  relations?: Relation[];
  /** Tutorial for new players (AW.A). */
  tutorial: Tutorial;
  /** Deferred consequences (LS.7). */
  scheduled: ScheduledEffect[];
  /** Pacing of dynamic events. */
  eventLog: { lastDay: number | null; lastByKind: Record<string, number> };
}

export interface ScheduledEffect {
  id: string;
  day: number;
  causeId: string;
  effect:
    | { kind: 'reputation'; delta: number }
    | { kind: 'competition'; topic: string; amount: number; company: string }
    | { kind: 'fix_bugs'; projectId: string };
}
